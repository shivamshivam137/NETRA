// Helper to concatenate turn-by-turn road segments from high-fidelity road cache
export function buildRoadCoords(camPairs) {
  const all = []
  for (const [from, to] of camPairs) {
    const key = `${from}_${to}`
    const rev = `${to}_${from}`
    const seg = roadCache[key]?.coordinates || (roadCache[rev] ? [...roadCache[rev].coordinates].reverse() : [])
    if (all.length > 0 && seg.length > 0) {
      all.push(...seg.slice(1))
    } else if (seg.length > 0) {
      all.push(...seg)
    }
  }
  return all
}

