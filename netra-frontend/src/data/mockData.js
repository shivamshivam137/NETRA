// Helper to look up trajectory by plate or vehicle ID
export const getVehicleTrajectory = (plateOrId) => {
  if (!plateOrId) return null
  const cleanStr = String(plateOrId).replace(/[\s\-_]/g, '').toUpperCase()
  return trajectories.find(t => 
    t.plate.replace(/[\s\-_]/g, '').toUpperCase() === cleanStr ||
    t.vehicleId.toUpperCase() === cleanStr
  ) || null
}

